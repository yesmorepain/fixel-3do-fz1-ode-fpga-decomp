#!/usr/bin/env python3
"""Write the two designs for the formal equivalence check (tools/formal/formal.sh).

Usage: python3 tools/formal/mkformal.py [build/sim/chip_sim.v] [build/formal]

gold.v: the decoded netlist (tools/mksim.py output) as module `gold`; gate.v: the clean core (hdl/) as module `gate`.
Both get the same ports:
  inputs   every input pin, the CD data pins (read side; inouts are cut into an input and a driver),
           sim_pll_clk (PLL output) and sim_osc_clk (clock of the output-enable power-up regs)
  outputs  per driven pin X: e_pin_X (driver enable) and v_pin_X (enable & value)
The golden LUT loops (n592 n629 n615 n596 n440 n575 n455 n375: one LUT whose output feeds back into itself) are
rewritten as level-sensitive latches `if (en) q = d`, after checking the LUT's truth table is exactly that.
"""
import itertools
import os
import re
import sys

src = sys.argv[1] if len(sys.argv) > 1 else 'build/sim/chip_sim.v'
out = sys.argv[2] if len(sys.argv) > 2 else 'build/formal'
os.makedirs(out, exist_ok=True)
t = open(src).read()

LOOPS = ['n592', 'n629', 'n615', 'n596', 'n440', 'n575', 'n455', 'n375']


def ev(e, env):
    """Evaluate a LUT expression (nets, 1'b0/1, !, ?:, parentheses) for the given net values."""
    toks = re.findall(r"1'b[01]|\w+|[()?:!]", e)
    pos = [0]

    def peek():
        return toks[pos[0]] if pos[0] < len(toks) else None

    def take():
        pos[0] += 1
        return toks[pos[0] - 1]

    def atom():
        x = take()
        if x == '(':
            v = cond()
            assert take() == ')'
            return v
        if x == '!':
            return 1 - atom()
        if x.startswith("1'b"):
            return int(x[-1])
        return env[x]

    def cond():
        c = atom()
        if peek() == '?':
            take()
            a = cond()
            assert take() == ':'
            b = cond()
            return a if c else b
        return c
    v = cond()
    assert pos[0] == len(toks), e
    return v


for q in LOOPS:
    m = re.search(r'^/\* FF [^*]*\*/ assign %s = (n\d+);$' % q, t, re.M)
    lut = m.group(1)
    m = re.search(r'^assign %s\s*=\s*(/\*[^*]*\*/)\s*(.*);$' % lut, t, re.M)
    expr = m.group(2)
    nets = sorted(set(re.findall(r'\bn\d+\b', expr)) - {q})
    found = None
    for en in nets:
        rest = [n for n in nets if n != en]
        ok = True
        for vals in itertools.product((0, 1), repeat=len(rest)):
            env = dict(zip(rest, vals))
            hold = [ev(expr, dict(env, **{q: vq, en: 0})) for vq in (0, 1)]
            load = [ev(expr, dict(env, **{q: vq, en: 1})) for vq in (0, 1)]
            ok &= hold == [0, 1] and load[0] == load[1]
        if ok:
            found = en
    assert found, '%s: LUT %s is not a latch: %s' % (q, lut, expr)
    en = found
    # d: the LUT with en = 1 (q drops out)
    d = re.sub(r'\b%s\b' % q, "1'b0", re.sub(r'\b%s\b' % en, "1'b1", expr))
    new = 'reg %s; always @* if (%s) %s = %s;   // mkformal: LUT loop of %s = latch (truth table checked)' % (
        lut, en, lut, d, q)
    t = t[:m.start()] + new + t[m.end():]
    t = re.sub(r'^wire (.*)\b%s\b,? ?' % lut, lambda mm: mm.group(0).replace(lut + ', ', '').replace(', ' + lut, ''),
               t, count=0, flags=re.M)
    print('%s: latch en=%s d=%s (LUT %s)' % (q, en, d, lut))

# pins: drivers become e_/v_ outputs, inouts become inputs
drv = re.findall(r'^assign (pin_\d+) = (\w+) \? (\w+) : 1\'bz;$', t, re.M)
for p, e, v in drv:
    t = t.replace("assign %s = %s ? %s : 1'bz;" % (p, e, v),
                  'assign e_%s = %s; assign v_%s = %s & %s;' % (p, e, p, e, v))
driven = [p for p, _, _ in drv]
hdr = re.search(r'module chip \((.*?)\);', t, re.S)
ins = [p for p in re.findall(r'(?:input|inout) (\w+)', hdr.group(1)) if p != 'pin_44']
ports = ', '.join(['input %s' % p for p in ins] + ['output e_%s, output v_%s' % (p, p) for p in sorted(driven)])
t = t[:hdr.start()] + 'module gold (%s);' % ports + t[hdr.end():]
open(os.path.join(out, 'gold.v'), 'w').write(t)

# clean core with the same ports (enables and values as compared by the co-sim, tools/sim/mkcosim.py)
bus = ['pin_6', 'pin_9', 'pin_10', 'pin_11', 'pin_12', 'pin_13', 'pin_18', 'pin_19']
val = {'pin_14': 'so', 'pin_42': 'gpio21', 'pin_38': 'gpio20', 'pin_4': 'cdsten_n', 'pin_44': 'cddten_n',
       'pin_2': 'cdmdchg', 'pin_45': "1'b1", 'pin_25': "1'b1", 'pin_34': "1'b1", 'pin_23': 'pin_15',
       'pin_36': 'pin_15'}
L = ['// generated by tools/formal/mkformal.py: clean core with the golden netlist\'s formal ports',
     'module gate (%s);' % ports,
     '  wire [7:0] cdd_out; wire cdd_drive, oe, so, gpio21, gpio20, cdsten_n, cddten_n, cdmdchg;',
     '  ode_fpga_core clean(.clk_osc(pin_37), .clk(sim_pll_clk), .clk_oe(sim_osc_clk), .rst(pin_43),',
     '    .spi_sck(pin_15), .spi_ss_n(pin_16), .spi_mosi(pin_17), .spi_miso(so), .cmd_ready(gpio21),',
     '    .data_free(gpio20), .cden_n(pin_48), .cdhwr_n(pin_47), .cdhrd_n(pin_46), .cdcmd_n(pin_3),',
     '    .cdd_in({%s}), .cdd_out(cdd_out),' % ', '.join(bus[::-1]),
     '    .cdd_drive(cdd_drive), .cdsten_n(cdsten_n), .cddten_n(cddten_n), .cdmdchg(cdmdchg), .oe_ready(oe));']
for p in sorted(driven):
    if p in bus:
        L.append("  assign e_%s = oe & cdd_drive; assign v_%s = oe & cdd_drive & cdd_out[%d];" % (p, p, bus.index(p)))
    else:
        L.append('  assign e_%s = oe; assign v_%s = oe & %s;' % (p, p, val[p]))
L.append('endmodule')
open(os.path.join(out, 'gate.v'), 'w').write('\n'.join(L) + '\n')
print('wrote %s/gold.v, %s/gate.v (%d driven pins)' % (out, out, len(driven)))

# RAM cut-points (formal.sh removes the SB_RAM40_4K instances with `expose -evert`): paired by function and WDATA
# wiring (both designs put the same data bits on the same RAM data pins). RDATA becomes a shared free input; the
# obligations are the RAM's write event, write address and data, read event and read address, and both clocks.
RAMS = [('ram40_19_1', 'clean.cmd_ram.ram'), ('ram40_19_3', 'clean.reply_ram.ram'),
        ('ram40_19_9', 'clean.sec_ram.ram_[0].ram'), ('ram40_19_7', 'clean.sec_ram.ram_[1].ram'),
        ('ram40_19_5', 'clean.sec_ram.ram_[2].ram'), ('ram40_19_11', 'clean.sec_ram.ram_[3].ram')]
pins = re.findall(r'(input|output) (\w+)', ports)
W = ['// generated by tools/formal/mkformal.py: designs with RAM cut-points, identical ports']
rports = []
for k in range(len(RAMS)):
    rports += ['input [15:0] r%d_q' % k] + ['output r%d_%s' % (k, x) for x in ('wclk', 'we', 'rclk', 're')] + \
              ['output [10:0] r%d_wa' % k, 'output [15:0] r%d_wd' % k, 'output [10:0] r%d_ra' % k]
for mod, col in (('gold', 0), ('gate', 1)):
    W.append('module %s_w (%s);' % (mod, ', '.join(['%s %s' % (d, n) for d, n in pins] + rports)))
    conn = ['.%s(%s)' % (n, n) for _, n in pins]
    for k, r in enumerate(RAMS):
        nm = r[col]
        for x in ('WDATA', 'WADDR', 'WE', 'WCLKE', 'WCLK', 'RADDR', 'RE', 'RCLKE', 'RCLK', 'MASK'):
            W.append('  wire [%d:0] r%d_%s;' % ({'WDATA': 15, 'MASK': 15, 'WADDR': 10, 'RADDR': 10}.get(x, 0), k, x))
            conn.append('.\\%s__%s (r%d_%s)' % (nm, x, k, x))
        conn.append('.\\%s__RDATA (r%d_q)' % (nm, k))
        W.append('  assign r%d_wclk = r%d_WCLK; assign r%d_we = r%d_WE & r%d_WCLKE;' % ((k,) * 5))
        W.append("  assign r%d_wa = r%d_we ? r%d_WADDR : 11'd0; assign r%d_wd = r%d_we ? r%d_WDATA & ~r%d_MASK : 16'd0;"
                 % ((k,) * 7))
        W.append('  assign r%d_rclk = r%d_RCLK; assign r%d_re = r%d_RE & r%d_RCLKE;' % ((k,) * 5))
        W.append("  assign r%d_ra = r%d_re ? r%d_RADDR : 11'd0;" % ((k,) * 3))
    W.append('  %s u(%s);' % (mod, ', '.join(conn)))
    W.append('endmodule')
open(os.path.join(out, 'wrap.v'), 'w').write('\n'.join(W) + '\n')
print('wrote %s/wrap.v (%d RAM cut-points)' % (out, len(RAMS)))
