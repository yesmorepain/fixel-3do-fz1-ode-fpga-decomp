#!/usr/bin/env python3
"""Write the co-simulation wrapper (see cosim.sh). Usage: mkcosim.py TESTBENCH.v OUT.v

The wrapper is a module `chip` with the netlist's ports. It instantiates chip_ref (the decoded netlist) and
ode_fpga_core (clean HDL), passes every dut.nXXX the testbench reads through to the reference, and compares the
pin drivers of both designs (value and enable).
"""
import re
import sys

tb, out = sys.argv[1], sys.argv[2]
nets = sorted(set(re.findall(r'\bdut\.(n\d+)\b', open(tb).read())), key=lambda s: int(s[1:]))

bus = ['pin_6', 'pin_9', 'pin_10', 'pin_11', 'pin_12', 'pin_13', 'pin_18', 'pin_19']   # CDD0-7
# (pin, reference enable, reference value, clean enable, clean value)
cmp = [
    ('pin_14', 'golden.n585', 'golden.n611', 'oe', 'so'),
    ('pin_42', 'golden.n28', 'golden.n29', 'oe', 'gpio21'),
    ('pin_38', 'golden.n27', 'golden.n7', 'oe', 'gpio20'),
    ('pin_4', 'golden.n20', 'golden.n32', 'oe', 'cdsten_n'),
    ('pin_44', 'golden.n13', 'golden.n7', 'oe', 'cddten_n'),
    ('pin_2', 'golden.n19', 'golden.n21', 'oe', 'cdmdchg'),
    ('pin_45', 'golden.n14', 'golden.n9', 'oe', "1'b1"),
    ('pin_25', 'golden.n488', 'golden.n9', 'oe', "1'b1"),
    ('pin_34', 'golden.n111', 'golden.n9', 'oe', "1'b1"),
    ('pin_23', 'golden.n487', 'pin_15', 'oe', 'pin_15'),
    ('pin_36', 'golden.n26', 'pin_15', 'oe', 'pin_15'),
]
ref_bus = [('golden.n71', 'golden.n642'), ('golden.n215', 'golden.n636'), ('golden.n216', 'golden.n637'), ('golden.n371', 'golden.n635'),
           ('golden.n372', 'golden.n638'), ('golden.n438', 'golden.n634'), ('golden.n556', 'golden.n641'), ('golden.n557', 'golden.n640')]
for k, (p, (e, v)) in enumerate(zip(bus, ref_bus)):
    cmp.append((p, e, v, 'oe & cdd_drive', 'cdd_out[%d]' % k))

ports = ('input pin_37, input sim_pll_clk, input sim_osc_clk, inout pin_44, input pin_15, input pin_46, '
         'input pin_47, input pin_48, output pin_45, output pin_2, input pin_3, input pin_43, output pin_42, '
         'output pin_38, output pin_4, output pin_36, inout pin_6, output pin_34, inout pin_9, inout pin_10, '
         'inout pin_11, inout pin_12, inout pin_13, output pin_23, output pin_25, input pin_16, inout pin_19, '
         'inout pin_18, output pin_14, input pin_17')
conn = ', '.join('.%s(%s)' % (p, p) for p in re.findall(r'(pin_\d+|sim_\w+)', ports))
L = []
L.append('// generated by tools/sim/mkcosim.py: netlist vs. clean HDL lockstep wrapper')
L.append('`timescale 1ps/1ps')
L.append('module chip (%s);' % ports)
L.append('  chip_ref golden(%s);' % conn)
for n in nets:
    L.append('  wire %s = golden.%s;' % (n, n))
L.append('  wire [7:0] cdd_out; wire cdd_drive, oe, so, gpio21, gpio20, cdsten_n, cddten_n, cdmdchg;')
L.append('  ode_fpga_core clean(.clk_osc(pin_37), .clk(sim_pll_clk), .clk_oe(sim_osc_clk), .rst(pin_43),')
L.append('    .spi_sck(pin_15), .spi_ss_n(pin_16), .spi_mosi(pin_17), .spi_miso(so), .cmd_ready(gpio21),')
L.append('    .data_free(gpio20), .cden_n(pin_48), .cdhwr_n(pin_47), .cdhrd_n(pin_46), .cdcmd_n(pin_3),')
L.append('    .cdd_in({pin_19, pin_18, pin_13, pin_12, pin_11, pin_10, pin_9, pin_6}), .cdd_out(cdd_out),')
L.append('    .cdd_drive(cdd_drive), .cdsten_n(cdsten_n), .cddten_n(cddten_n), .cdmdchg(cdmdchg), .oe_ready(oe));')
L.append('  // pin driver of each design: value when enabled, z when not')
r = ', '.join("(%s ? %s : 1'bz)" % (e, v) for _, e, v, _, _ in cmp)
c = ', '.join("(%s ? %s : 1'bz)" % (e, v) for _, _, _, e, v in cmp)
L.append('  wire [%d:0] rdrv = {%s};' % (len(cmp) - 1, r))
L.append('  wire [%d:0] cdrv = {%s};' % (len(cmp) - 1, c))
L.append('  function [8*8-1:0] pname(input integer i); case (i) %s default: pname = "?"; endcase endfunction'
         % ' '.join('%d: pname = "%s";' % (i, p) for i, (p, *_) in enumerate(cmp)))
L.append('  integer k, sckn = 0, sckp1 = -100;')
L.append('  always @(posedge golden.n89) sckp1 = sckn;')
L.append('  always @(negedge pin_16) sckn = 0;')
L.append('  always @(posedge pin_15) if (!pin_16) sckn = sckn + 1;')
L.append('  // the only accepted difference: only SO differs, in the byte after the 0x01 opcode (port flag rising), and H bit 4 is 1')
L.append("  wire known_race = (rdrv[%d] !== cdrv[%d]) && (rdrv[%d:0] === cdrv[%d:0]) && golden.n89 && golden.n523 && sckn - sckp1 <= 8;"
         % ((len(cmp) - 1,) * 2 + (len(cmp) - 2,) * 2))
L.append('  always @(rdrv or cdrv) begin')
L.append('    #1;')
L.append('    if (rdrv !== cdrv && cosim_report.armed && known_race) begin')
L.append('      cosim_report.races = cosim_report.races + 1;')
L.append('      if (cosim_report.races <= 5) $display("COSIM known race %0t ps: SO byte 1 of a 0x01 packet (status bit 4 vs. H bit 4)", $time);')
L.append('    end else if (rdrv !== cdrv && cosim_report.armed) begin')
L.append('      cosim_report.count = cosim_report.count + 1;')
L.append('      if (cosim_report.count <= 20)')
L.append('        for (k = 0; k < %d; k = k + 1)' % len(cmp))
L.append('          if (rdrv[%d - k] !== cdrv[%d - k])' % (len(cmp) - 1, len(cmp) - 1))
N1 = len(cmp) - 1
L.append('            $display("COSIM MISMATCH %%0t ps %%0s: ref=%%b clean=%%b", $time, pname(k), rdrv[%d - k], cdrv[%d - k]);'
         % (N1, N1))
L.append('    end')
L.append('  end')
L.append('endmodule')
L.append('')
L.append('// mismatch counter; armed after the first pin 43 pulse ends (before that the reference has x in its IO regs)')
L.append('module cosim_report;')
L.append('  integer count = 0, races = 0; reg armed = 0;')
L.append('  always @(negedge tb.pin_43) armed = 1;')
L.append('  final $display("COSIM SUMMARY: %0d mismatching driver changes, %0d known-race differences (%0s)", count, races, armed ? "armed" : "NEVER ARMED");')
L.append('endmodule')
open(out, 'w').write('\n'.join(L) + '\n')
